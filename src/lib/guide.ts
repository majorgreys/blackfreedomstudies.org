import { getCollection } from 'astro:content';
import guide from '../data/guide/guide.json';

export interface Moment { t: string; c: string; v: string; k: number; a: number; s: number; n: string; x: string }
export interface Unit { key: string; title: string; intro: string; topics: string[]; stops: Moment[]; more: Moment[] }
export interface Transcript { paragraphs: [number, string][]; moments: Omit<Moment, 'v' | 'x'>[] }

export const parts = guide.parts as { name: string; units: Unit[] }[];
export const units = parts.flatMap(p => p.units);
export const finder = guide.finder as Moment[];
export const recordings = guide.recordings as Record<string, { date: string; kind: string; title: string }>;

// Full transcripts are generated by scripts/build-guide-data.py; pages are built only for those present.
const files = import.meta.glob<{ default: Transcript }>('../data/guide/transcripts/*.json', { eager: true });
export const transcripts = new Map(
  Object.entries(files).map(([path, mod]) => [path.split('/').pop()!.replace('.json', ''), mod.default]),
);

export const hms = (s: number) => {
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), sec = String(s % 60).padStart(2, '0');
  return h ? `${h}:${String(m).padStart(2, '0')}:${sec}` : `${m}:${sec}`;
};
export const youtubeUrl = (v: string, k?: number) => `https://www.youtube.com/watch?v=${v}${k ? `&t=${k}s` : ''}`;
export const transcriptUrl = (v: string, a?: number) => `/guide/recordings/${v}/${a === undefined ? '' : `#t-${a}`}`;
export const formatDate = (d: string) =>
  new Date(`${d}T00:00:00Z`).toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' });

// The site's own event title and page where one matches the recording's date.
export async function recordingInfo() {
  const events = await getCollection('events');
  const byDate = new Map(events.map(e => [e.data.date.toISOString().slice(0, 10), e]));
  return Object.fromEntries(Object.entries(recordings).map(([v, r]) => {
    const e = r.date < '2013' ? undefined : byDate.get(r.date);
    return [v, {
      ...r,
      title: e?.data.title ?? r.title,
      eventUrl: e ? `/events/${e.data.seasonPart}-${e.data.seasonYear}/${e.id}` : null,
      hasTranscript: transcripts.has(v),
    }];
  }));
}
export type RecordingInfo = Awaited<ReturnType<typeof recordingInfo>>;
